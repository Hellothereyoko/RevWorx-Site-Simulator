CREATE OR REPLACE FUNCTION public.app_user_id()
RETURNS integer
LANGUAGE sql
STABLE
SET search_path = pg_catalog
AS $$
  SELECT NULLIF(current_setting('app.user_id', true), '')::integer
$$;

CREATE OR REPLACE FUNCTION public.app_customer_id()
RETURNS integer
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT u.customerid
  FROM public."User" AS u
  WHERE u.userid = public.app_user_id()
$$;

CREATE OR REPLACE FUNCTION public.app_is_owner()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public."User" AS u
    JOIN public.role AS r ON r.roleid = u.roleid
    WHERE u.userid = public.app_user_id()
      AND r.rolename IN ('Admin', 'Owner')
  )
$$;

CREATE OR REPLACE FUNCTION public.app_can_view_project(p_project_id integer)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT public.app_is_owner() OR EXISTS (
    SELECT 1
    FROM public.project AS p
    WHERE p.projectid = p_project_id
      AND p.customerid = public.app_customer_id()
  )
$$;

CREATE OR REPLACE FUNCTION public.app_can_view_lead(p_lead_id integer)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT public.app_is_owner() OR EXISTS (
    SELECT 1
    FROM public.lead AS l
    WHERE l.leadid = p_lead_id
      AND l.customerid = public.app_customer_id()
  )
$$;

CREATE OR REPLACE FUNCTION public.get_login_user_by_email(p_email text)
RETURNS TABLE (
  user_id integer,
  email text,
  password_hash text,
  role_name text,
  customer_id integer
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT u.userid, u.email::text, u.passwordhash::text, r.rolename::text, u.customerid
  FROM public."User" AS u
  JOIN public.role AS r ON r.roleid = u.roleid
  WHERE u.email = p_email
$$;

CREATE OR REPLACE FUNCTION public.submit_contact_form(
  p_name varchar(100),
  p_email varchar(255),
  p_phone varchar(20),
  p_message text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_customer_id integer;
  v_inquiry_status_id integer;
BEGIN
  IF p_name IS NULL OR char_length(btrim(p_name)) NOT BETWEEN 1 AND 100
     OR p_email IS NULL OR char_length(p_email) NOT BETWEEN 1 AND 254
     OR p_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
     OR char_length(COALESCE(p_phone, '')) > 20
     OR p_message IS NULL OR char_length(btrim(p_message)) NOT BETWEEN 1 AND 5000 THEN
    RAISE EXCEPTION 'Invalid contact form submission' USING ERRCODE = '22023';
  END IF;

  SELECT statusid INTO v_inquiry_status_id
  FROM public.leadstatus
  WHERE statusname = 'Inquiry';

  IF v_inquiry_status_id IS NULL THEN
    RAISE EXCEPTION 'The Inquiry lead status is not configured';
  END IF;

  INSERT INTO public.customer (name, email, phone)
  VALUES (btrim(p_name), btrim(p_email), NULLIF(btrim(p_phone), ''))
  RETURNING customerid INTO v_customer_id;

  INSERT INTO public.lead (customerid, summary, statusid, submissiondate)
  VALUES (v_customer_id, btrim(p_message), v_inquiry_status_id, CURRENT_DATE);
END
$$;

