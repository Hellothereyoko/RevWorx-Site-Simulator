CREATE TABLE IF NOT EXISTS Role (
  roleID INT PRIMARY KEY,
  roleName VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS Customer (
  customerID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(255) NOT NULL,
  phone VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS "User" (
  userID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  passwordHash VARCHAR(255) NOT NULL,
  roleID INT NOT NULL REFERENCES Role(roleID),
  customerID INT REFERENCES Customer(customerID)
);

CREATE TABLE IF NOT EXISTS LeadStatus (
  statusID INT PRIMARY KEY,
  statusName VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS Lead (
  leadID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customerID INT NOT NULL REFERENCES Customer(customerID),
  summary TEXT NOT NULL,
  statusID INT NOT NULL REFERENCES LeadStatus(statusID),
  submissionDate DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS ProjectStatus (
  statusID INT PRIMARY KEY,
  statusName VARCHAR(50) NOT NULL UNIQUE,
  statusOrder INT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS Project (
  projectID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customerID INT NOT NULL REFERENCES Customer(customerID),
  leadID INT NOT NULL UNIQUE REFERENCES Lead(leadID),
  statusID INT NOT NULL REFERENCES ProjectStatus(statusID),
  projectName VARCHAR(100) NOT NULL,
  description TEXT
);

CREATE TABLE IF NOT EXISTS ProjectStatusHistory (
  historyID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  projectID INT NOT NULL REFERENCES Project(projectID),
  prevID INT REFERENCES ProjectStatus(statusID),
  newID INT NOT NULL REFERENCES ProjectStatus(statusID),
  changedAt TIMESTAMP NOT NULL,
  changedBy INT NOT NULL REFERENCES "User"(userID)
);

CREATE TABLE IF NOT EXISTS Attachment (
  attachmentID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  projectID INT NOT NULL REFERENCES Project(projectID),
  uploadedBy INT NOT NULL REFERENCES "User"(userID),
  fileName VARCHAR(255) NOT NULL,
  storagePath VARCHAR(500) NOT NULL,
  uploadedAt TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS Communication (
  communicationID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  projectID INT NOT NULL REFERENCES Project(projectID),
  userID INT NOT NULL REFERENCES "User"(userID),
  content TEXT NOT NULL CHECK (LENGTH(TRIM(content)) > 0),
  createdAt TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS Feedback (
  feedbackID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  projectID INT NOT NULL REFERENCES Project(projectID),
  content TEXT NOT NULL CHECK (LENGTH(TRIM(content)) > 0),
  submittedAt TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS Notification (
  notificationID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  userID INT NOT NULL REFERENCES "User"(userID),
  projectID INT NOT NULL REFERENCES Project(projectID),
  message TEXT NOT NULL,
  createdAt TIMESTAMP NOT NULL,
  readAt TIMESTAMP
);

CREATE TABLE IF NOT EXISTS FollowUp (
  followUpID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  userID INT NOT NULL REFERENCES "User"(userID),
  leadID INT REFERENCES Lead(leadID),
  projectID INT REFERENCES Project(projectID),
  description TEXT NOT NULL,
  dueDate DATE NOT NULL,
  completedAt TIMESTAMP,
  CONSTRAINT chk_followup_lead_or_project_xor CHECK (
    (leadID IS NOT NULL AND projectID IS NULL) OR
    (leadID IS NULL AND projectID IS NOT NULL)
  )
);

